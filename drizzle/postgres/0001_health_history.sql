-- Additive storage required by the health timeline and rot reports.
-- Apply before deploying this release. Existing bookmarks and jobs are retained.
DO $migration$
BEGIN
  CREATE TABLE IF NOT EXISTS fihrist.health_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES neon_auth."user"(id) ON DELETE CASCADE,
    trigger TEXT NOT NULL CHECK (trigger IN ('weekly','manual','single')),
    status TEXT NOT NULL DEFAULT 'running' CHECK (status IN ('running','completed')),
    total INTEGER NOT NULL DEFAULT 0,
    checked INTEGER NOT NULL DEFAULT 0,
    started_at TIMESTAMPTZ, completed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (id,user_id)
  );
  ALTER TABLE fihrist.bookmarks ADD COLUMN IF NOT EXISTS health_alert_dismissed_at TIMESTAMPTZ;
  ALTER TABLE fihrist.bookmark_jobs ADD COLUMN IF NOT EXISTS run_id BIGINT REFERENCES fihrist.health_runs(id) ON DELETE SET NULL;
  ALTER TABLE fihrist.health_check_settings ADD COLUMN IF NOT EXISTS last_run_id BIGINT REFERENCES fihrist.health_runs(id) ON DELETE SET NULL;
  CREATE TABLE IF NOT EXISTS fihrist.health_checks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES neon_auth."user"(id) ON DELETE CASCADE,
    bookmark_id BIGINT NOT NULL,
    run_id BIGINT,
    job_id BIGINT REFERENCES fihrist.bookmark_jobs(id) ON DELETE SET NULL,
    checked_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    status TEXT NOT NULL CHECK (status IN ('healthy','redirected','broken','needs_review')),
    http_status INTEGER, final_url TEXT, duration_ms INTEGER, error TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (bookmark_id,user_id) REFERENCES fihrist.bookmarks(id,user_id) ON DELETE CASCADE,
    FOREIGN KEY (run_id,user_id) REFERENCES fihrist.health_runs(id,user_id) ON DELETE CASCADE
  );
  CREATE TABLE IF NOT EXISTS fihrist.rot_digests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES neon_auth."user"(id) ON DELETE CASCADE,
    run_id BIGINT NOT NULL UNIQUE,
    facts TEXT NOT NULL, narrative TEXT,
    narrative_status TEXT NOT NULL DEFAULT 'none' CHECK (narrative_status IN ('none','ok','failed')),
    model TEXT, prompt_tokens INTEGER, completion_tokens INTEGER, estimated_prompt_tokens INTEGER,
    read_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (run_id,user_id) REFERENCES fihrist.health_runs(id,user_id) ON DELETE CASCADE
  );
  CREATE INDEX IF NOT EXISTS health_checks_bookmark_idx ON fihrist.health_checks(bookmark_id,checked_at);
  CREATE INDEX IF NOT EXISTS health_checks_run_idx ON fihrist.health_checks(run_id);
  CREATE INDEX IF NOT EXISTS rot_digests_user_idx ON fihrist.rot_digests(user_id,created_at);
  GRANT SELECT,INSERT,UPDATE,DELETE ON fihrist.health_runs,fihrist.health_checks,fihrist.rot_digests TO fihrist_runtime;
  GRANT USAGE,SELECT ON SEQUENCE fihrist.health_runs_id_seq,fihrist.health_checks_id_seq,fihrist.rot_digests_id_seq TO fihrist_runtime;
END
$migration$;
