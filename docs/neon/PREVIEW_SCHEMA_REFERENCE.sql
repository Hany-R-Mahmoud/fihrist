CREATE SCHEMA IF NOT EXISTS fihrist;

CREATE TABLE IF NOT EXISTS fihrist.collections (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES neon_auth."user"(id) ON DELETE CASCADE,
  name TEXT NOT NULL CHECK (char_length(name) BETWEEN 1 AND 160),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT collections_user_name_unique UNIQUE(user_id, name),
  CONSTRAINT collections_id_user_unique UNIQUE(id, user_id)
);

CREATE TABLE IF NOT EXISTS fihrist.bookmarks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES neon_auth."user"(id) ON DELETE CASCADE,
  collection_id BIGINT,
  url TEXT NOT NULL,
  normalized_url TEXT NOT NULL,
  normalized_url_hash TEXT NOT NULL,
  host TEXT NOT NULL,
  title TEXT,
  description TEXT,
  favicon_url TEXT,
  image_url TEXT,
  notes TEXT,
  content_text TEXT,
  language TEXT,
  content_direction TEXT NOT NULL DEFAULT 'ltr' CHECK(content_direction IN ('ltr','rtl')),
  analysis_summary TEXT,
  saved_reason TEXT,
  saving_benefit TEXT,
  analysis_status TEXT NOT NULL DEFAULT 'pending' CHECK(analysis_status IN ('pending','processing','ready','failed')),
  analysis_error TEXT,
  analyzed_at TIMESTAMPTZ,
  ingestion_status TEXT NOT NULL DEFAULT 'pending' CHECK(ingestion_status IN ('pending','processing','ready','failed')),
  scrape_error TEXT,
  health_status TEXT NOT NULL DEFAULT 'unchecked' CHECK(health_status IN ('unchecked','healthy','redirected','broken','needs_review')),
  http_status INT,
  last_checked_at TIMESTAMPTZ,
  health_error TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT bookmarks_user_urlhash_unique UNIQUE(user_id, normalized_url_hash),
  CONSTRAINT bookmarks_id_user_unique UNIQUE(id, user_id),
  CONSTRAINT bookmarks_collection_ownership_fk FOREIGN KEY(collection_id,user_id)
    REFERENCES fihrist.collections(id,user_id) ON DELETE SET NULL (collection_id)
);

CREATE TABLE IF NOT EXISTS fihrist.tags (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES neon_auth."user"(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  normalized_name TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT tags_user_normalized_unique UNIQUE(user_id, normalized_name),
  CONSTRAINT tags_id_user_unique UNIQUE(id, user_id)
);

CREATE TABLE IF NOT EXISTS fihrist.bookmark_tags (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES neon_auth."user"(id) ON DELETE CASCADE,
  bookmark_id BIGINT NOT NULL,
  tag_id BIGINT NOT NULL,
  source TEXT NOT NULL DEFAULT 'automatic' CHECK(source IN ('automatic','manual','ai')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT bookmark_tags_unique UNIQUE(bookmark_id, tag_id),
  CONSTRAINT bookmark_tags_bookmark_owner_fk FOREIGN KEY(bookmark_id,user_id)
    REFERENCES fihrist.bookmarks(id,user_id) ON DELETE CASCADE,
  CONSTRAINT bookmark_tags_tag_owner_fk FOREIGN KEY(tag_id,user_id)
    REFERENCES fihrist.tags(id,user_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS fihrist.bookmark_jobs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES neon_auth."user"(id) ON DELETE CASCADE,
  bookmark_id BIGINT NOT NULL,
  type TEXT NOT NULL CHECK(type IN ('scrape','health_check')),
  status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','processing','completed','failed')),
  attempt_count INT NOT NULL DEFAULT 0 CHECK(attempt_count >= 0),
  error TEXT,
  available_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  queued_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  started_at TIMESTAMPTZ,
  lease_until TIMESTAMPTZ,
  lease_token TEXT,
  completed_at TIMESTAMPTZ,
  CONSTRAINT bookmark_jobs_bookmark_owner_fk FOREIGN KEY(bookmark_id,user_id)
    REFERENCES fihrist.bookmarks(id,user_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS fihrist.ai_tag_suggestions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES neon_auth."user"(id) ON DELETE CASCADE,
  bookmark_id BIGINT NOT NULL,
  tag_name TEXT NOT NULL,
  normalized_name TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','approved','rejected')),
  prompt_tokens INT,
  completion_tokens INT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT ai_tag_suggestions_unique UNIQUE(user_id,bookmark_id,normalized_name),
  CONSTRAINT ai_tag_suggestions_bookmark_owner_fk FOREIGN KEY(bookmark_id,user_id)
    REFERENCES fihrist.bookmarks(id,user_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS fihrist.health_check_settings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES neon_auth."user"(id) ON DELETE CASCADE,
  enabled BOOLEAN NOT NULL DEFAULT true,
  last_run_at TIMESTAMPTZ,
  last_run_started_at TIMESTAMPTZ,
  last_run_total INT,
  last_run_completed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT health_check_settings_user_unique UNIQUE(user_id)
);

CREATE INDEX IF NOT EXISTS fihrist_bookmarks_user_created_idx ON fihrist.bookmarks(user_id,created_at DESC,id DESC);
CREATE INDEX IF NOT EXISTS fihrist_bookmarks_user_health_idx ON fihrist.bookmarks(user_id,health_status);
CREATE INDEX IF NOT EXISTS fihrist_bookmarks_user_analysis_idx ON fihrist.bookmarks(user_id,analysis_status);
CREATE INDEX IF NOT EXISTS fihrist_bookmarks_user_collection_idx ON fihrist.bookmarks(user_id,collection_id);
CREATE INDEX IF NOT EXISTS fihrist_bookmark_tags_bookmark_idx ON fihrist.bookmark_tags(bookmark_id);
CREATE INDEX IF NOT EXISTS fihrist_bookmark_tags_tag_idx ON fihrist.bookmark_tags(tag_id);
CREATE INDEX IF NOT EXISTS fihrist_bookmark_jobs_pending_idx ON fihrist.bookmark_jobs(status,type,available_at,queued_at);
CREATE INDEX IF NOT EXISTS fihrist_bookmark_jobs_lease_idx ON fihrist.bookmark_jobs(status,lease_until);
CREATE INDEX IF NOT EXISTS fihrist_bookmark_jobs_user_idx ON fihrist.bookmark_jobs(user_id);
CREATE INDEX IF NOT EXISTS fihrist_ai_tags_bookmark_status_idx ON fihrist.ai_tag_suggestions(bookmark_id,status);

